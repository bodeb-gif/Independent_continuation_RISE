"""Build the journal manuscript package from saved results; no model/API calls."""
from pathlib import Path
import hashlib
import json
import os
import re
import shutil
import zipfile

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT/'data/scored/proquest'
OUT = BASE/'paper_jcss_v1'
PACKAGE = ROOT/'paper/overleaf/jcss_submission'


def digest(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main():
    os.environ.setdefault('MPLCONFIGDIR', '/tmp/bode-paper-mpl')
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    source = BASE/'reverify300_20261022/summary.json'
    d = json.loads(source.read_text())
    OUT.mkdir(exist_ok=True)
    plt.rcParams.update({'font.family':'DejaVu Sans','font.size':10,'pdf.fonttype':42})
    fig, axes = plt.subplots(1,2,figsize=(9.2,3.4),sharex=True)
    for ax,frame,title in zip(axes,['historical_1900_2010','modern_2011_2026'],['Historical audit (250 claims)','Modern audit (50 claims)']):
        for j,who in enumerate(['reviewer1','reviewer2']):
            color=['#165b8b','#a35420'][j]
            for i,field in enumerate(['inclusion','direction','horizon_months']):
                if field=='inclusion':
                    m=d['groups'][frame][who]
                    a,b=m['before_precision_bounds'][0],m['after_precision_bounds'][0]
                else:
                    m=d['field_comparison'][frame][who][field]
                    a,b=m['before']['fraction'],m['after']['fraction']
                y=2-i+(0.13 if j==0 else -0.13)
                ax.plot([a*100,b*100],[y,y],color=color,lw=2)
                ax.plot(a*100,y,'o',ms=6,mfc='white',mec=color,label=f'Reviewer {j+1}: before' if i==0 else None)
                ax.plot(b*100,y,'s',ms=5,mfc=color,mec=color,label=f'Reviewer {j+1}: after' if i==0 else None)
        ax.set_title(title,fontsize=11)
        ax.set_yticks([2,1,0],['Inclusion','Direction','Horizon'])
        ax.set_xlim(58,95);ax.set_ylim(-.45,2.45)
        ax.set_xlabel('Sample agreement / precision (%)')
        ax.grid(axis='x',alpha=.25);ax.set_axisbelow(True)
        for edge in ['top','right']:ax.spines[edge].set_visible(False)
    handles,labels=axes[0].get_legend_handles_labels()
    fig.legend(handles,labels,loc='lower center',ncol=4,frameon=False,fontsize=9)
    fig.tight_layout(rect=(0,.13,1,1))
    fig.savefig(OUT/'validation_stages.pdf',bbox_inches='tight')
    fig.savefig(OUT/'validation_stages.png',dpi=180,bbox_inches='tight')
    plt.close(fig)
    manuscript=ROOT/'paper/manuscript/low_cost_extraction.tex'
    text=manuscript.read_text()
    abstract=re.search(r'\\abstract\{(.*?)\}\s*\\keywords',text,re.S).group(1)
    assert 150<=len(abstract.split())<=250
    assert len(re.search(r'\\keywords\{([^}]+)\}',text).group(1).split(','))==6
    stale=['Inter-reviewer agreement has not','Inter-reviewer agreement remains uncalculated','inter-reviewer agreement and adjudication remain unmeasured']
    assert not any(x in text for x in stale)
    PACKAGE.mkdir(parents=True,exist_ok=True)
    text=re.sub(r'\\graphicspath\{.*?\}\n','',text)
    figures={'validation_stages.pdf':('Fig2.pdf',OUT),
             'employment_sensitivity.pdf':('Fig3.pdf',BASE/'paper_low_cost_v1')}
    # Remove retired generated assets from the previously built package.
    for retired in ['Fig4.pdf', 'Fig5.pdf']:
        (PACKAGE/retired).unlink(missing_ok=True)
    for old,(new,folder) in figures.items():
        text=text.replace('{'+old+'}','{'+new+'}')
        shutil.copyfile(folder/old,PACKAGE/new)
    (PACKAGE/'main.tex').write_text(text)
    shutil.copyfile(ROOT/'paper/manuscript/sn-jnl.cls',PACKAGE/'sn-jnl.cls')
    (PACKAGE/'README.txt').write_text('''JOURNAL OF COMPUTATIONAL SOCIAL SCIENCE — AUTHOR REVIEW DRAFT

Compile main.tex using pdfLaTeX, twice or until references settle. The official
Springer Nature class is supplied with iicol and numeric citation options.
All compilation dependencies are in this directory; BibTeX is not required.
The workflow figure is editable LaTeX, and other figures are vector PDFs.

The authoritative manuscript is paper/manuscript/low_cost_extraction.tex in the
repository. This flat package is regenerated by scripts/build_jcss_package.py.
Edit that source before rebuilding to keep copies synchronized.

Author name and email were supplied by the author. Affiliation, funding,
competing interests, contributions, ethics determination, and a permanent data
archive or reviewer-access URL still need author confirmation. No submission
has been made. See paper/submission/jcss/READINESS.md in the repository.
''')
    file_names=['main.tex','sn-jnl.cls','README.txt']+[new for new,_ in figures.values()]
    manifest={'target_journal':'Journal of Computational Social Science','article_type':'full research article',
              'status':'revised author-review draft; declarations and archive details pending',
              'source_manuscript_sha256':digest(manuscript),'validation_input_sha256':digest(source),
              'abstract_words_whitespace':len(abstract.split()),'keywords_n':6,
              'template_url':'https://cms-resources.apps.public.k8s.springernature.io/springer-cms/rest/v1/content/18782940/data/v12',
              'sha256':{name:digest(PACKAGE/name) for name in file_names}}
    (PACKAGE/'MANIFEST.json').write_text(json.dumps(manifest,indent=2)+'\n')
    dest=ROOT/'output/overleaf/jcss_submission.zip';dest.parent.mkdir(parents=True,exist_ok=True)
    with zipfile.ZipFile(dest,'w',zipfile.ZIP_DEFLATED) as z:
        for name in file_names+['MANIFEST.json']:z.write(PACKAGE/name,name)
    (OUT/'source_manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(json.dumps({'abstract_words':len(abstract.split()),'package':str(dest),'files':len(file_names)+1}))


if __name__=='__main__':
    main()
